    await admin.getByLabel('Store name', { exact: true }).fill('Browser Demo Store — edited')
    await admin.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(admin.getByRole('cell', { name: 'Browser Demo Store — edited', exact: true })).toBeVisible()
    await capture(admin, 'store-administration.png')
    await admin.getByRole('link', { name: 'Technicians', exact: true }).click()
